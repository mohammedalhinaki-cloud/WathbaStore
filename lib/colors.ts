/**
 * هل اللون (HEX) داكن؟
 *
 * تُستخدم لضبط تباين نصوص الفوتر مع خلفيته: عندما يختار صاحب المتجر
 * لونًا داكنًا لخلفية الفوتر تصبح النصوص بيضاء صريحة (#FFFFFF) أو
 * أوف-وايت (#F3F4F6) بلا أي شفافية، وعندما تكون الخلفية فاتحة (أو غير
 * مضبوطة) تبقى النصوص الداكنة الافتراضية — فلا ينكسر التباين في الحالتين.
 *
 * الصيغ المدعومة: #RGB و #RRGGBB. أي قيمة أخرى (اسم لون مثلًا) تُعامَل
 * كغير داكنة حتى لا نخاطر بنص أبيض فوق خلفية فاتحة.
 */
export function isDarkColor(input: string): boolean {
  const hex = (input || "").trim().replace(/^#/, "");
  if (!/^[0-9a-f]{3}$|^[0-9a-f]{6}$/i.test(hex)) return false;
  const full =
    hex.length === 3
      ? hex
          .split("")
          .map((c) => c + c)
          .join("")
      : hex;
  const r = parseInt(full.slice(0, 2), 16);
  const g = parseInt(full.slice(2, 4), 16);
  const b = parseInt(full.slice(4, 6), 16);
  // معادلة YIQ للإدراك البصري للسطوع (0–255): أقل من 130 ⇒ داكن
  return (r * 299 + g * 587 + b * 114) / 1000 < 130;
}
